-- =====================================================================
-- V15: sys_user 增加 email 列 —— 支撑 C 端学员邮箱注册功能
-- ---------------------------------------------------------------------
-- 1. email 列可空：存量用户（教师/管理员/历史种子学生）不强制回填，
--    登录仍走用户名路径；
-- 2. 唯一性以「部分唯一索引」表达：仅对未删除且有值的行生效——
--    允许多行 email IS NULL（PG 对 NULL 不判等），软删行亦不占坑；
-- 3. 登录侧新增「用户名或邮箱」回退查询时依赖该列 + 本索引保证
--    selectOne 结果唯一。
-- =====================================================================

ALTER TABLE sys_user ADD COLUMN email VARCHAR(255);

CREATE UNIQUE INDEX uniq_sys_user_email
    ON sys_user (email)
    WHERE deleted = 0 AND email IS NOT NULL;
